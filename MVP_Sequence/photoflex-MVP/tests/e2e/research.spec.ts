  await page.getByRole("button", { name: "Bridge.jpg" }).click();
  await page.locator(".research-picker input[type=file]").setInputFiles({
    name: "reference.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+X2iUAAAAASUVORK5CYII=", "base64"),
  });
