import { expect, test, type Page } from "@playwright/test";

async function seedResearchProject(page: Page) {
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto("/");
  return page.evaluate(async () => {
    const fixture = "/tests/helpers/browserProjectFixture.ts";
    const { createBrowserWorkspace } = await import(/* @vite-ignore */ fixture);
    const id = crypto.randomUUID();
    const createdAt = new Date().toISOString();
    const sourceId = "field-source", photoId = "field-photo", relativePath = "Bridge.jpg";
    const canvas = document.createElement("canvas");
    canvas.width = 80;
    canvas.height = 60;
    const context = canvas.getContext("2d")!;
    context.fillStyle = "#7d8a78";
    context.fillRect(0, 0, canvas.width, canvas.height);
    const blob = await new Promise<Blob>((resolve) => canvas.toBlob((image) => resolve(image!), "image/jpeg"));
    const request = indexedDB.open("photoflex-mvp");
    const db = await new Promise<IDBDatabase>((resolve, reject) => { request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error); });
    const tx = db.transaction(["projects", "photo-index", "photo-thumbnails"], "readwrite");
    tx.objectStore("projects").put(createBrowserWorkspace({ projectId: id, name: "Field work", createdAt,
      sources: [{ id: sourceId, displayName: "Field photos", createdAt }],
    }));
    tx.objectStore("photo-index").put({ id: photoId, sourceId, relativePath, width: 800, height: 600 });
    tx.objectStore("photo-thumbnails").put({ photoId, maxEdge: 512, sourceVersion: `${relativePath}|800|600|unknown-size|unknown-mtime|unknown-fingerprint`, blob });
    await new Promise<void>((resolve, reject) => { tx.oncomplete = () => resolve(); tx.onabort = () => reject(tx.error); });
    db.close();
    return id;
  });
}

