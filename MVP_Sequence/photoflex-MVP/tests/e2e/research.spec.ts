test("Table notes can be edited in place and deleted from the canvas or Research list", async ({ page }) => {
  const projectId = await seedResearchProject(page);
  await page.goto(`/#/projects/${projectId}/table`);
  const rail = page.locator(".table-tools-rail");
  const newNote = rail.getByRole("button", { name: "New research note", exact: true });
  await expect(rail.locator(".table-rail-creation button").first()).toHaveAccessibleName("New research note");
  const sourcePhoto = page.getByRole("button", { name: "Bridge.jpg", exact: true });
  await sourcePhoto.click();
  await expect(sourcePhoto).toHaveAttribute("aria-pressed", "true");
  await expect(newNote).toHaveAccessibleDescription("New research note with selected photos");
  await newNote.click();
  await expect(page).toHaveURL(new RegExp(`/projects/${projectId}/table$`));
  const cards = page.locator(".table-research-card");
  const title = page.getByRole("textbox", { name: "Note title" });
  await expect(cards.first().getByRole("textbox", { name: "Note title" })).toBeFocused();
  await expect(title).toHaveCSS("outline-style", "none");
  await expect(cards.first()).toHaveCSS("outline-style", "none");
  await title.fill("Bridge study");
  const card = page.getByRole("article", { name: /Research note · Bridge study/ });
  await expect(card.getByText("1 image", { exact: true })).toBeVisible();
  await expect(card.locator(".research-image-view img")).toBeVisible();
  const text = "Bridge at dusk 雨 📷";
  const cardBody = card.getByRole("textbox", { name: "Note body" });
  await cardBody.fill(text);
  await expect(cardBody).toHaveText(text);
  await expect(cardBody).toHaveCSS("outline-style", "none");
  await expect(card).toHaveCSS("outline-style", "none");
  await cardBody.locator("p").first().click({ position: { x: 1, y: 8 } });
  await page.keyboard.press("Delete");
  await expect(cardBody).toHaveText(text.slice(1));
  const confirm = page.getByRole("dialog", { name: "Delete note" });
  await expect(confirm).toHaveCount(0);
  await card.getByRole("button", { name: "Open note" }).click();
  await expect(page.getByRole("textbox", { name: "Note body" }).locator("p").first()).toHaveText(text.slice(1));
  await expect(page.getByRole("textbox", { name: "Image caption" })).toHaveCount(1);
  await page.getByRole("button", { name: "Back to Table" }).click();

  const x = await card.evaluate((element) => Number.parseFloat(element.style.left));
  const handle = await card.getByRole("button", { name: "Move note card" }).boundingBox();
  await page.mouse.move(handle!.x + 30, handle!.y + 12);
  await page.mouse.down();
  await page.mouse.move(handle!.x + 62, handle!.y + 12, { steps: 4 });
  await page.mouse.up();
  await expect(card).toHaveCSS("left", `${x + 32}px`);
  await expect(card).toHaveCSS("outline-style", "solid");

  await newNote.click();
  await cards.last().getByRole("textbox", { name: "Note title" }).fill("Sidebar note");
  await newNote.click();
  await cards.last().getByRole("textbox", { name: "Note title" }).fill("Keyboard note");
  const keyboardCard = page.getByRole("article", { name: /Research note · Keyboard note/ });
  await keyboardCard.getByRole("button", { name: "Move note card" }).press("Delete");
  await expect(confirm).toContainText("Keyboard note");
  await confirm.getByRole("button", { name: "Delete note" }).click();
  await expect(cards).toHaveCount(2);

  await card.getByRole("button", { name: "Delete note" }).click();
  await expect(confirm).toContainText("Bridge study");
  await confirm.getByRole("button", { name: "Cancel" }).click();
  await expect(card).toBeVisible();
  await card.getByRole("button", { name: "Open note" }).click();
  const list = page.getByRole("complementary", { name: "Research notes" });
  await expect(list.getByRole("button", { name: "Keyboard note", exact: true })).toHaveCount(0);
  await list.getByRole("button", { name: "Delete note “Sidebar note”" }).click();
  await confirm.getByRole("button", { name: "Delete note" }).click();
  await expect(list.getByRole("button", { name: "Sidebar note", exact: true })).toHaveCount(0);
  await expect(title).toHaveValue("Bridge study");
  await page.getByRole("button", { name: "Back to Table" }).click();
  await expect(cards).toHaveCount(1);
  await expect(card).toHaveCSS("left", `${x + 32}px`);
  await card.getByRole("button", { name: "Delete note" }).click();
  await confirm.getByRole("button", { name: "Delete note" }).click();
  await expect(cards).toHaveCount(0);
  await page.reload();
  await expect(newNote).toBeVisible();
  await expect(cards).toHaveCount(0);
});
